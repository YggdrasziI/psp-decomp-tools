#!/usr/bin/env python3
"""Turn back into plain values the symbol references that the PRX does not relocate.

spimdisasm guesses addresses from `lui`/`addiu` pairs and data words; some of the
guesses are plain constants that happen to fall inside the module (0x76B10, 0).
The PRX relocation tables say which words really hold addresses, so every
symbolic `%hi`/`%lo` operand or `.word <symbol>` of the splat output without a
relocation at that address gets a `MIPS_NONE` override (`%gp_rel` operands need no
relocation in a PRX and are left alone).

Output: config/<version>/reloc_addrs.<module>.txt (generated, committed; read by splat
through `reloc_addrs_path`). Entries already in the file are kept, since the
next split no longer shows them as symbols. Run after a split, then split again:
    python tools/psp/reloc_overrides.py && python tools/configure.py
"""

import argparse
import re
from pathlib import Path

import project
from prx import Prx

ROOT = project.ROOT

# /* <rom> <vram> <bytes> */ followed by an instruction or directive
LINE = re.compile(r"^\s*/\* ([0-9A-F]+) ([0-9A-F]{8}) [0-9A-F]{8} \*/\s+(.*)$")
INSN_REF = re.compile(r"%(?:hi|lo)\(([A-Za-z_.$][\w.$]*)")
WORD_REF = re.compile(r"^\.word\s+([A-Za-z_.$][\w.$]*)")
ENTRY = re.compile(r"^rom:0x([0-9A-F]+) reloc:MIPS_NONE")


def relocated_vrams(prx: Prx) -> set[int]:
    bases = [seg.vaddr for seg in prx.segments]
    return {bases[r.offset_seg] + r.offset for r in prx.relocs()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", default=project.DEFAULT_VERSION)
    parser.add_argument("--module", default=project.DEFAULT_MODULE, help="module of decomp.toml")
    args = parser.parse_args()

    prx = Prx(project.module_file(args.version, args.module))
    relocated = relocated_vrams(prx)
    out_path = project.config_dir(args.version) / f"reloc_addrs.{args.module}.txt"

    roms = set()
    if out_path.exists():
        for line in out_path.read_text().splitlines():
            if m := ENTRY.match(line):
                roms.add(int(m.group(1), 16))
    before = len(roms)

    for path in sorted(project.asm_dir(args.version, args.module).rglob("*.s")):
        for line in path.read_text().splitlines():
            m = LINE.match(line)
            if not m:
                continue
            rom, vram, text = int(m.group(1), 16), int(m.group(2), 16), m.group(3)
            if (INSN_REF.search(text) or WORD_REF.match(text)) and vram not in relocated:
                roms.add(rom)

    lines = ["// Generated by reloc_overrides.py: symbol references the PRX does not",
             "// relocate (plain values). Do not edit."]
    # splat requires a symbol attribute even for MIPS_NONE; it is not used
    lines += [f"rom:0x{rom:06X} reloc:MIPS_NONE symbol:none" for rom in sorted(roms)]
    out_path.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{out_path.relative_to(ROOT)}: {len(roms)} entries ({len(roms) - before} new)")


if __name__ == "__main__":
    main()
