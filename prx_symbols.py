#!/usr/bin/env python3
"""Write the splat symbols that the PRX itself proves: import stubs (named from
their NID), module exports (standard SDK NIDs) and the import/export tables.

Output: config/<version>/symbol_addrs.<module>.txt (generated, committed). Hand-made
names go in config/<version>/symbol_addrs.txt.

NID names come from config/nids.txt, built from PPSSPP's HLE tables with
--ppsspp (see README.md). A NID without a name gives
<library>_<NID>; the names of the "mcp" library (exported by the game's
EBOOT) are unknown.
"""

import argparse
import re
import struct
from pathlib import Path

import project
from prx import Prx

ROOT = project.ROOT
# A project may keep its own list; the shared one comes with the tools
NIDS_PATH = ROOT / "config" / "nids.txt"
if not NIDS_PATH.exists():
    NIDS_PATH = project.TOOLS / "nids.txt"

# Standard module export NIDs of the PSP SDK
EXPORT_NIDS = {
    0xD632ACDB: "module_start",
    0xCEE8593C: "module_stop",
    0xF01D73A7: "module_info",
    0x11B97506: "module_sdk_version",
    0x0F7C276C: "module_start_thread_parameter",
    0xCF0CC697: "module_stop_thread_parameter",
}
FUNCTION_EXPORTS = {"module_start", "module_stop"}


def build_nid_db(ppsspp: Path) -> None:
    """Collect the {NID, wrapper, "name"} entries of PPSSPP's HLE tables."""
    entry = re.compile(r'\{\s*0[xX]([0-9A-Fa-f]{8})\s*,[^"\n]*"([A-Za-z_][A-Za-z_0-9]*)"')
    names: dict[int, str] = {}
    for src in sorted((ppsspp / "Core" / "HLE").glob("*.cpp")):
        for nid, name in entry.findall(src.read_text(encoding="utf-8", errors="replace")):
            names.setdefault(int(nid, 16), name)
    lines = [f"{nid:08X} {name}" for nid, name in sorted(names.items())]
    NIDS_PATH.write_text(
        "# NID -> function name, from PPSSPP Core/HLE/*.cpp (prx_symbols.py --ppsspp)\n"
        + "\n".join(lines) + "\n", newline="\n")
    print(f"{NIDS_PATH}: {len(lines)} NIDs")


def load_nid_db() -> dict[int, str]:
    names = {}
    for line in NIDS_PATH.read_text().splitlines():
        if line and not line.startswith("#"):
            nid, name = line.split()
            names[int(nid, 16)] = name
    return names


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-v", "--version", default=project.DEFAULT_VERSION)
    parser.add_argument("-m", "--module", default=project.DEFAULT_MODULE)
    parser.add_argument("--prx", type=Path, default=None)
    parser.add_argument("--ppsspp", type=Path, help="Rebuild config/nids.txt from a PPSSPP checkout")
    args = parser.parse_args()

    if args.ppsspp:
        build_nid_db(args.ppsspp)
    nid_names = load_nid_db()

    prx = Prx(args.prx or project.module_file(args.version, args.module))
    info = prx.module_info()
    out: list[str] = []

    def sym(name: str, addr: int, kind: str | None = None, size: int | None = None) -> None:
        attrs = []
        if kind:
            attrs.append(f"type:{kind}")
        if size:
            attrs.append(f"size:{size:#x}")
        out.append(f"{name} = 0x{addr:08X}; // " + " ".join(attrs) if attrs
                   else f"{name} = 0x{addr:08X};")

    out.append("// Generated by prx_symbols.py from the module tables, do not edit")
    out.append("")
    out.append("// Module exports (.lib.ent)")
    ent = prx.section(".lib.ent")
    _, _, _, _, var_count, func_count, table = struct.unpack_from("<IHHBBHI", prx.data, ent.offset)
    count = var_count + func_count
    for i in range(count):
        nid, addr = prx.u32(table + 4 * i), prx.u32(table + 4 * (count + i))
        name = EXPORT_NIDS.get(nid, f"export_{nid:08X}")
        sym(name, addr, "func" if name in FUNCTION_EXPORTS else None)
    sym("__lib_ent_top", prx.section(".lib.ent.top").addr)
    sym("__library_exports", ent.addr)
    sym("__lib_ent_bottom", prx.section(".lib.ent.btm").addr)
    sym("__lib_stub_top", prx.section(".lib.stub.top").addr)
    sym("__library_imports", info["stub_top"])
    sym("__lib_stub_bottom", prx.section(".lib.stub.btm").addr)

    unknown = 0
    for imp in prx.imports():
        out.append("")
        out.append(f"// Imports from {imp.library}")
        for nid, stub in zip(imp.nids, imp.stub_addrs):
            name = nid_names.get(nid)
            if name is None:
                name = f"{imp.library}_{nid:08X}"
                unknown += 1
            sym(name, stub, "func", 8)
    path = project.config_dir(args.version) / f"symbol_addrs.{args.module}.txt"
    path.write_text("\n".join(out) + "\n", newline="\n")
    print(f"{path.relative_to(ROOT)}: {sum(1 for l in out if ' = ' in l)} symbols, "
          f"{unknown} imports without a known name")


if __name__ == "__main__":
    main()
